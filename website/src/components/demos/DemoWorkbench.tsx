import { useEffect, useRef, useState } from "react";
import { useInView } from "motion/react";
import { DemoProvider, useDemo } from "../../lib/demo-context";
import { GcodeViewer } from "./GcodeViewer";
import { PrinterCatalog } from "./PrinterCatalog";
import { SliceSettingsDemo } from "./SliceSettingsDemo";
import { CliTerminal } from "./CliTerminal";
import { McpChat } from "./McpChat";
import { LaunchRace } from "./LaunchRace";
import { FieldThemePicker } from "./FieldThemePicker";

function ToolpathPanel() {
  const { data, layer, setLayer, playing, setPlaying, showTravel, setShowTravel } = useDemo();
  const [buildProgress, setBuildProgress] = useState(1);
  const max = (data?.layers.length ?? 1) - 1;

  useEffect(() => {
    if (!playing || !data) return;
    let prog = 0;
    const id = window.setInterval(() => {
      prog += 0.08;
      if (prog >= 1) {
        prog = 0;
        setLayer((l) => {
          if (l >= max) {
            setPlaying(false);
            return max;
          }
          return l + 1;
        });
      }
      setBuildProgress(prog);
    }, 55);
    return () => clearInterval(id);
  }, [playing, data, max, setLayer, setPlaying]);

  const source = data?.source ?? "";

  return (
    <section className="demo-panel demo-panel--toolpath" id="toolpath">
      <header className="demo-panel__head">
        <div>
          <h2 className="demo-panel__title">T-wing toolpath</h2>
          <p className="demo-panel__note">
            {source || "Real CuraEngine G-code generated by Shale · 0.2 mm · A1."}
          </p>
        </div>
        <div className="toolpath-controls">
          <label className="travel-toggle">
            <input
              type="checkbox"
              checked={showTravel}
              onChange={(e) => setShowTravel(e.target.checked)}
            />
            Travel
          </label>
          <input
            type="range"
            min={0}
            max={max}
            value={layer}
            onChange={(e) => {
              setBuildProgress(1);
              setLayer(Number(e.target.value));
            }}
            aria-label="Layer"
          />
          <button
            type="button"
            className="btn btn--ghost"
            onClick={() => {
              if (playing) {
                setPlaying(false);
                return;
              }
              // At rest the slider sits on the last layer so the still is the
              // finished T-wing. Restart from the bed when the user hits Play.
              if (layer >= max) {
                setLayer(0);
                setBuildProgress(0);
              }
              setPlaying(true);
            }}
          >
            {playing ? "Pause" : "Play layers"}
          </button>
        </div>
      </header>
      <GcodeViewer
        data={data}
        layerIndex={layer}
        showTravel={showTravel}
        buildProgress={buildProgress}
        linesOnly
        className="demo-panel__viewer gcode-viewer--toolpath"
      />
    </section>
  );
}

function DemosInner() {
  const root = useRef(null);
  const inView = useInView(root, { margin: "-10% 0px", once: true });

  return (
    <div ref={root} className={`demos-workbench ${inView ? "demos-workbench--live" : ""}`}>
      <div className="demos-workbench__grid">
        <ToolpathPanel />
        <PrinterCatalog autoStart={inView} />
        <SliceSettingsDemo />
        <CliTerminal autoStart={inView} />
        <McpChat autoStart={inView} />
        <section className="demo-panel demo-panel--launch">
          <header className="demo-panel__head">
            <h2 className="demo-panel__title">Cold vs warm launch</h2>
          </header>
          <LaunchRace />
        </section>
        <section className="demo-panel demo-panel--theme">
          <FieldThemePicker />
        </section>
      </div>
    </div>
  );
}

export default function DemoWorkbench() {
  return (
    <DemoProvider eager>
      <DemosInner />
    </DemoProvider>
  );
}