/**
 * Parse CuraEngine G-code (Shale output) into trim JSON for the site viewer.
 * Usage: node gcode-to-json.mjs <in.gcode> <out.json> [--travel] [--step=0.25]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const args = process.argv.slice(2);
const inPath = args[0];
const outPath = args[1];
const includeTravel = args.includes("--travel");
const stepArg = args.find((a) => a.startsWith("--step="));
const stepMm = stepArg ? Number(stepArg.split("=")[1]) : 0.35;
const layerDecimate = 1; // keep every layer

if (!inPath || !outPath) {
  console.error("Usage: node gcode-to-json.mjs <in.gcode> <out.json>");
  process.exit(1);
}

const text = readFileSync(inPath, "utf8");
const lines = text.split("\n");

let meta = {
  filament_m: 0,
  time_s: 0,
  layer_height_mm: 0.2,
  minX: 0,
  minY: 0,
  minZ: 0,
  maxX: 0,
  maxY: 0,
  maxZ: 0,
};
for (const line of lines) {
  if (line.startsWith(";TIME:")) meta.time_s = Number(line.slice(6));
  if (line.startsWith(";Filament used:")) meta.filament_m = Number(line.slice(15).replace(/m$/, ""));
  if (line.startsWith(";Layer height:")) meta.layer_height_mm = Number(line.slice(14));
  if (line.startsWith(";MINX:")) meta.minX = Number(line.slice(6));
  if (line.startsWith(";MINY:")) meta.minY = Number(line.slice(6));
  if (line.startsWith(";MINZ:")) meta.minZ = Number(line.slice(6));
  if (line.startsWith(";MAXX:")) meta.maxX = Number(line.slice(6));
  if (line.startsWith(";MAXY:")) meta.maxY = Number(line.slice(6));
  if (line.startsWith(";MAXZ:")) meta.maxZ = Number(line.slice(6));
}

const bedCenter = { x: 128, y: 128 };
const typeMap = {
  "WALL-OUTER": "wall-outer",
  "WALL-INNER": "wall-inner",
  SKIN: "skin",
  FILL: "infill",
  SUPPORT: "support",
  SKIRT: "skirt",
  "SKIRT/BRIM": "skirt",
};

/** @type {Map<number, { z: number, segments: { type: string, points: number[][] }[] }>} */
const layerMap = new Map();
let layerIndex = 0;
let curType = "travel";
let x = 0,
  y = 0,
  z = 0;
let lastE = null;

function ensureLayer(li) {
  if (!layerMap.has(li)) {
    const lh = meta.layer_height_mm || 0.2;
    layerMap.set(li, { z: round(meta.minZ + (li + 1) * lh), segments: [] });
  }
  return layerMap.get(li);
}

function mapType(t) {
  const key = t.replace(";TYPE:", "").trim();
  return typeMap[key] ?? "other";
}

function local(xg, yg) {
  return [round(xg - bedCenter.x), round(yg - bedCenter.y)];
}

function pushPoint(li, type, px, py) {
  const lay = ensureLayer(li);
  let seg = lay.segments[lay.segments.length - 1];
  if (!seg || seg.type !== type) {
    seg = { type, points: [] };
    lay.segments.push(seg);
  }
  const pts = seg.points;
  const next = [px, py];
  if (pts.length === 0) {
    pts.push(next);
    return;
  }
  const last = pts[pts.length - 1];
  const d = Math.hypot(next[0] - last[0], next[1] - last[1]);
  if (d < stepMm * 0.4) return;
  if (d > stepMm * 2.5) {
    const steps = Math.ceil(d / stepMm);
    for (let s = 1; s <= steps; s++) {
      const t = s / steps;
      pts.push([round(last[0] + t * (next[0] - last[0])), round(last[1] + t * (next[1] - last[1]))]);
    }
    return;
  }
  pts.push(next);
}

for (const raw of lines) {
  const line = raw.trim();
  if (!line) continue;
  if (line.startsWith(";LAYER:")) {
    layerIndex = Number(line.slice(7));
    continue;
  }
  if (line.startsWith(";TYPE:")) {
    curType = mapType(line);
    continue;
  }
  if (line.startsWith(";")) continue;

  const g = line.match(/^(G0|G1)\b/i);
  if (!g) continue;

  let nx = x,
    ny = y,
    nz = z,
    ne = lastE;
  const tok = /([XYZEF])(-?\d*\.?\d+)/gi;
  let m;
  while ((m = tok.exec(line))) {
    const v = Number(m[2]);
    if (m[1] === "X") nx = v;
    if (m[1] === "Y") ny = v;
    if (m[1] === "Z") nz = v;
    if (m[1] === "E") ne = v;
  }

  const isExtrude =
    g[1].toUpperCase() === "G1" && ne !== null && lastE !== null && ne > lastE + 1e-6;
  const isTravel = !isExtrude;

  if (isTravel && !includeTravel) {
    x = nx;
    y = ny;
    z = nz;
    lastE = ne ?? lastE;
    continue;
  }

  const [lx, ly] = local(nx, ny);
  const type = isTravel ? "travel" : curType === "travel" ? "infill" : curType;
  if (type === "skirt" && !includeTravel) continue;

  pushPoint(layerIndex, type, lx, ly);
  x = nx;
  y = ny;
  z = nz;
  lastE = ne ?? lastE;
}

let layers = [...layerMap.entries()]
  .sort((a, b) => a[0] - b[0])
  .map(([, v]) => v)
  .filter((l) => l.segments.length);

if (layerDecimate > 1) {
  layers = layers.filter((_, i) => i % layerDecimate === 0);
}

for (const lay of layers) {
  lay.segments = lay.segments.filter((s) => s.points.length >= 2);
}

const modelW = meta.maxX - meta.minX;
const modelH = meta.maxY - meta.minY;

const payload = {
  source: `Real CuraEngine G-code generated by Shale (Cura_SteamEngine 5.13.0) · ${basename(inPath)}`,
  meta: {
    ...meta,
    layers: layers.length,
    bounds: {
      minX: meta.minX,
      maxX: meta.maxX,
      minY: meta.minY,
      maxY: meta.maxY,
      minZ: meta.minZ,
      maxZ: meta.maxZ,
    },
    model_mm: [modelW, modelH, meta.maxZ - meta.minZ],
  },
  plate_mm: 256,
  layers,
};

const json = JSON.stringify(payload);
writeFileSync(outPath, json);
console.log(`Wrote ${outPath}: ${layers.length} layers, ${(json.length / 1024).toFixed(0)} KiB`);

function round(n) {
  return Math.round(n * 20) / 20;
}